#!/usr/bin/env python3
"""
Generate src/i18n_keys.h and src/i18n_data.c from tools/language_source.py
(the original MultiTool Python language table: 81 keys x 18 languages).
All output is pure ASCII (non-ASCII chars become \\xXXXX escapes), so it
compiles identically on MSVC / MinGW regardless of source code page.
"""
import importlib.util, os, sys

here = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("language_source", os.path.join(here, "language_source.py"))
m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)

LANGS = list(m.LANGUAGES.keys())
KEYS = list(m.TRANSLATIONS.keys())

def wlit(s):
    """Return a C wide string literal made only of ASCII."""
    out = []          # list of literal pieces
    cur = ""
    def flush():
        nonlocal cur
        if cur:
            out.append('L"' + cur + '"'); cur = ""
    for ch in s:
        o = ord(ch)
        if ch == '"': cur += '\\"'
        elif ch == '\\': cur += '\\\\'
        elif ch == '\n': cur += '\\n'
        elif 32 <= o < 127: cur += ch
        else:
            units = [o] if o < 0x10000 else [0xD800 + ((o - 0x10000) >> 10), 0xDC00 + ((o - 0x10000) & 0x3FF)]
            for u in units:
                cur += '\\x%04x' % u
                flush()          # break literal so following hex digits can't merge
    flush()
    return " ".join(out) if out else 'L""'

with open(os.path.join(here, "..", "src", "i18n", "i18n_keys.h"), "w", newline="\n") as f:
    f.write("/* AUTO-GENERATED by tools/gen_i18n.py - do not edit */\n#ifndef MT_I18N_KEYS_H\n#define MT_I18N_KEYS_H\n\n")
    f.write("#define LANG_COUNT %d\n\ntypedef enum I18nKey {\n" % len(LANGS))
    for k in KEYS: f.write("    K_%s,\n" % k)
    f.write("    K__COUNT\n} I18nKey;\n\n")
    f.write("extern const wchar_t* const g_lang_code[LANG_COUNT];\n")
    f.write("extern const wchar_t* const g_lang_name[LANG_COUNT];\n")
    f.write("extern const wchar_t* const g_lang_native[LANG_COUNT];\n")
    f.write("extern const wchar_t* const g_i18n[K__COUNT][LANG_COUNT];\n\n#endif\n")

with open(os.path.join(here, "..", "src", "i18n", "i18n_data.c"), "w", newline="\n") as f:
    f.write("/* AUTO-GENERATED by tools/gen_i18n.py - do not edit */\n#include <wchar.h>\n#include \"i18n/i18n_keys.h\"\n\n")
    f.write("const wchar_t* const g_lang_code[LANG_COUNT] = {\n")
    for l in LANGS: f.write("    %s,\n" % wlit(l))
    f.write("};\nconst wchar_t* const g_lang_name[LANG_COUNT] = {\n")
    for l in LANGS: f.write("    %s,\n" % wlit(m.LANGUAGES[l]["name"]))
    f.write("};\nconst wchar_t* const g_lang_native[LANG_COUNT] = {\n")
    for l in LANGS: f.write("    %s,\n" % wlit(m.LANGUAGES[l]["native"]))
    f.write("};\n\nconst wchar_t* const g_i18n[K__COUNT][LANG_COUNT] = {\n")
    for k in KEYS:
        f.write("    /* %s */ {\n" % k)
        for l in LANGS:
            f.write("        %s,\n" % wlit(m.TRANSLATIONS[k][l]))
        f.write("    },\n")
    f.write("};\n")
print("keys:", len(KEYS), "langs:", len(LANGS))
