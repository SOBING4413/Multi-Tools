#!/usr/bin/env python3
"""
Regenerates multitool.vcxproj and multitool.vcxproj.filters from the folder tree under src/.
Run it after adding / renaming / removing source files:   python tools/gen_vsproj.py
The Solution Explorer filters mirror the folders (src/ui/pages -> "src\\ui\\pages").
"""
import os, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SRC = os.path.join(ROOT, "src")
GUID_PROJ = "{B7E2F4A1-6C3D-4E8A-9F21-5D0A7C3B1E94}"

def collect(ext):
    out = []
    for d, dirs, files in os.walk(SRC):
        dirs.sort()
        for f in sorted(files):
            if f.endswith(ext):
                out.append(os.path.relpath(os.path.join(d, f), ROOT).replace("/", "\\"))
    return out

def filter_of(path):          # src\ui\pages\x.c -> src\ui\pages
    return os.path.dirname(path)

def all_filters(paths):
    fl = set()
    for p in paths:
        d = filter_of(p)
        while d:
            fl.add(d)
            d = os.path.dirname(d)
    return sorted(fl)

LIBS = ("gdi32.lib;user32.lib;advapi32.lib;shell32.lib;ole32.lib;oleaut32.lib;uuid.lib;comdlg32.lib;comctl32.lib;uxtheme.lib;"
        "dwmapi.lib;ws2_32.lib;iphlpapi.lib;winhttp.lib;netapi32.lib;setupapi.lib;cfgmgr32.lib;bcrypt.lib;wintrust.lib;"
        "crypt32.lib;psapi.lib;powrprof.lib;msimg32.lib")

CONFS = [("Debug", "Win32"), ("Release", "Win32"), ("Debug", "x64"), ("Release", "x64")]
cs, hs = collect(".c"), collect(".h")

def cond(c, p): return f"'$(Configuration)|$(Platform)'=='{c}|{p}'"

def idg(c, p):
    dbg = c == "Debug"
    return f'''  <ItemDefinitionGroup Condition="{cond(c, p)}">
    <ClCompile>
      <WarningLevel>Level3</WarningLevel>
      <SDLCheck>false</SDLCheck>
      <ConformanceMode>true</ConformanceMode>
      <LanguageStandard_C>stdc11</LanguageStandard_C>
      <CompileAs>CompileAsC</CompileAs>
      <AdditionalIncludeDirectories>$(ProjectDir)src;$(ProjectDir)res;%(AdditionalIncludeDirectories)</AdditionalIncludeDirectories>
      <AdditionalOptions>/utf-8 %(AdditionalOptions)</AdditionalOptions>
      <PreprocessorDefinitions>UNICODE;_UNICODE;WIN32_LEAN_AND_MEAN;NOMINMAX;_CRT_SECURE_NO_WARNINGS;_WINSOCK_DEPRECATED_NO_WARNINGS;_WIN32_WINNT=0x0A00;WINVER=0x0A00;{"_DEBUG" if dbg else "NDEBUG"};%(PreprocessorDefinitions)</PreprocessorDefinitions>
      <DisableSpecificWarnings>4996;4189;4100;4244;4267;4018;4146;4152;4204;4054;4055</DisableSpecificWarnings>
      <RuntimeLibrary>{"MultiThreadedDebug" if dbg else "MultiThreaded"}</RuntimeLibrary>
      <Optimization>{"Disabled" if dbg else "MaxSpeed"}</Optimization>
      <ObjectFileName>$(IntDir)%(RelativeDir)</ObjectFileName>
{"" if dbg else "      <FunctionLevelLinking>true</FunctionLevelLinking>" + chr(10) + "      <IntrinsicFunctions>true</IntrinsicFunctions>" + chr(10)}    </ClCompile>
    <ResourceCompile>
      <AdditionalIncludeDirectories>$(ProjectDir)res;$(ProjectDir)src;%(AdditionalIncludeDirectories)</AdditionalIncludeDirectories>
      <PreprocessorDefinitions>UNICODE;_UNICODE;%(PreprocessorDefinitions)</PreprocessorDefinitions>
      <Culture>0x0409</Culture>
    </ResourceCompile>
    <Link>
      <SubSystem>Windows</SubSystem>
      <GenerateDebugInformation>{"true" if dbg else "false"}</GenerateDebugInformation>
{"" if dbg else "      <EnableCOMDATFolding>true</EnableCOMDATFolding>" + chr(10) + "      <OptimizeReferences>true</OptimizeReferences>" + chr(10)}      <AdditionalDependencies>{LIBS};%(AdditionalDependencies)</AdditionalDependencies>
    </Link>
  </ItemDefinitionGroup>'''

def cfgprops(c, p):
    dbg = c == "Debug"
    return f'''  <PropertyGroup Condition="{cond(c, p)}" Label="Configuration">
    <ConfigurationType>Application</ConfigurationType>
    <UseDebugLibraries>{"true" if dbg else "false"}</UseDebugLibraries>
    <PlatformToolset>v143</PlatformToolset>
    <CharacterSet>Unicode</CharacterSet>
{"" if dbg else "    <WholeProgramOptimization>true</WholeProgramOptimization>" + chr(10)}  </PropertyGroup>'''

proj = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/gen_vsproj.py - re-run the script after adding or moving source files. -->
<Project DefaultTargets="Build" xmlns="http://schemas.microsoft.com/developer/msbuild/2003">
  <ItemGroup Label="ProjectConfigurations">
''' + "\n".join(f'''    <ProjectConfiguration Include="{c}|{p}">
      <Configuration>{c}</Configuration>
      <Platform>{p}</Platform>
    </ProjectConfiguration>''' for c, p in CONFS) + f'''
  </ItemGroup>
  <PropertyGroup Label="Globals">
    <VCProjectVersion>17.0</VCProjectVersion>
    <Keyword>Win32Proj</Keyword>
    <ProjectGuid>{GUID_PROJ}</ProjectGuid>
    <RootNamespace>MultiTool</RootNamespace>
    <WindowsTargetPlatformVersion>10.0</WindowsTargetPlatformVersion>
    <ProjectName>multitool</ProjectName>
  </PropertyGroup>
  <Import Project="$(VCTargetsPath)\\Microsoft.Cpp.Default.props" />
''' + "\n".join(cfgprops(c, p) for c, p in CONFS) + '''
  <Import Project="$(VCTargetsPath)\\Microsoft.Cpp.props" />
  <ImportGroup Label="ExtensionSettings" />
  <ImportGroup Label="Shared" />
''' + "\n".join(f'''  <ImportGroup Label="PropertySheets" Condition="{cond(c, p)}">
    <Import Project="$(UserRootDir)\\Microsoft.Cpp.$(Platform).user.props" Condition="exists('$(UserRootDir)\\Microsoft.Cpp.$(Platform).user.props')" Label="LocalAppDataPlatform" />
  </ImportGroup>''' for c, p in CONFS) + f'''
  <PropertyGroup Label="UserMacros" />
  <PropertyGroup>
    <!-- OutDir / IntDir / CodeAnalysisRuleSet come from Directory.Build.props.
         The manifest is embedded ONCE by the manifest tool from the <Manifest> item below (res\\multitool.rc does not contain it under MSVC). -->
    <TargetName>multi-tool</TargetName>
    <LinkIncremental>false</LinkIncremental>
  </PropertyGroup>
''' + "\n".join(idg(c, p) for c, p in CONFS) + '''
  <ItemGroup>
''' + "\n".join(f'    <ClCompile Include="{s}" />' for s in cs) + '''
  </ItemGroup>
  <ItemGroup>
''' + "\n".join(f'    <ClInclude Include="{h}" />' for h in hs) + '''
    <ClInclude Include="res\\resource.h" />
  </ItemGroup>
  <ItemGroup>
    <ResourceCompile Include="res\\multitool.rc" />
  </ItemGroup>
  <ItemGroup>
    <Image Include="res\\app.ico" />
    <Manifest Include="res\\multitool.manifest" />
    <None Include="Directory.Build.props" />
    <None Include="multitool.ruleset" />
    <None Include="Makefile" />
    <None Include="CMakeLists.txt" />
    <None Include=".editorconfig" />
    <None Include="tools\\gen_i18n.py" />
    <None Include="tools\\gen_vsproj.py" />
    <None Include="tools\\make_ico.py" />
    <None Include="README.md" />
    <None Include="CHANGELOG.md" />
  </ItemGroup>
  <Import Project="$(VCTargetsPath)\\Microsoft.Cpp.targets" />
  <ImportGroup Label="ExtensionTargets" />
</Project>
'''
open(os.path.join(ROOT, "multitool.vcxproj"), "w", newline="\r\n", encoding="utf-8").write(proj)

# ------------------------------------------------ filters
ids = {}
def guid_for(name):
    import hashlib
    h = hashlib.md5(name.encode()).hexdigest().upper()
    return "{%s-%s-%s-%s-%s}" % (h[:8], h[8:12], h[12:16], h[16:20], h[20:32])

fl = all_filters(cs + hs)
f = '<?xml version="1.0" encoding="utf-8"?>\n<Project ToolsVersion="4.0" xmlns="http://schemas.microsoft.com/developer/msbuild/2003">\n  <ItemGroup>\n'
for name in fl:
    f += f'    <Filter Include="{name}"><UniqueIdentifier>{guid_for(name)}</UniqueIdentifier></Filter>\n'
f += f'    <Filter Include="res"><UniqueIdentifier>{guid_for("res")}</UniqueIdentifier></Filter>\n'
f += f'    <Filter Include="tools"><UniqueIdentifier>{guid_for("tools")}</UniqueIdentifier></Filter>\n'
f += f'    <Filter Include="build"><UniqueIdentifier>{guid_for("build")}</UniqueIdentifier></Filter>\n'
f += '  </ItemGroup>\n  <ItemGroup>\n'
for s in cs: f += f'    <ClCompile Include="{s}"><Filter>{filter_of(s)}</Filter></ClCompile>\n'
f += '  </ItemGroup>\n  <ItemGroup>\n'
for h in hs: f += f'    <ClInclude Include="{h}"><Filter>{filter_of(h)}</Filter></ClInclude>\n'
f += '    <ClInclude Include="res\\resource.h"><Filter>res</Filter></ClInclude>\n  </ItemGroup>\n  <ItemGroup>\n'
f += '    <ResourceCompile Include="res\\multitool.rc"><Filter>res</Filter></ResourceCompile>\n'
f += '    <Image Include="res\\app.ico"><Filter>res</Filter></Image>\n    <Manifest Include="res\\multitool.manifest"><Filter>res</Filter></Manifest>\n'
for n in ("Directory.Build.props", "multitool.ruleset", "Makefile", "CMakeLists.txt"):
    f += f'    <None Include="{n}"><Filter>build</Filter></None>\n'
for n in ("gen_i18n.py", "gen_vsproj.py", "make_ico.py"):
    f += f'    <None Include="tools\\{n}"><Filter>tools</Filter></None>\n'
f += '  </ItemGroup>\n</Project>\n'
open(os.path.join(ROOT, "multitool.vcxproj.filters"), "w", newline="\r\n", encoding="utf-8").write(f)

